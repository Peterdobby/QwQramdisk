"""Generate a fixed C registry from reviewed, exact keybagd binary profiles."""
import json
import re
from pathlib import Path


def generate_header(registry, destination):
    document = json.loads(Path(registry).read_text())
    if document.get("schema") != 1 or not document.get("profiles"):
        raise ValueError("invalid keybagd profile registry")
    lines = ["/* Generated by tools.keybagd_registry; edit keybagd-profiles.json. */"]
    sources = set()
    for index, profile in enumerate(document["profiles"]):
        if not re.fullmatch(r"13[A-Z][0-9]+", profile["build"]):
            raise ValueError("invalid keybagd build label")
        for field in ("source_sha256", "result_sha256"):
            if not re.fullmatch(r"[0-9a-f]{64}", profile[field]):
                raise ValueError(f"invalid {field}")
        if profile["source_sha256"] in sources:
            raise ValueError("duplicate keybagd source hash")
        sources.add(profile["source_sha256"])
        if not 8 <= profile["size"] <= 16 * 1024 * 1024 or profile["paths"] < 1:
            raise ValueError("invalid keybagd size/path count")
        if not profile["patches"]:
            raise ValueError("keybagd profile has no patches")
        offsets = set()
        lines.append(f"static const struct patch registry_patches_{index}[] = {{")
        for patch in profile["patches"]:
            off = patch["offset"]
            if off % 4 or off < 0 or off + 4 > profile["size"] or off in offsets:
                raise ValueError("invalid/duplicate patch offset")
            offsets.add(off)
            before, after = bytes.fromhex(patch["before"]), bytes.fromhex(patch["after"])
            if len(before) != 4 or len(after) != 4 or before == after:
                raise ValueError("invalid patch instruction")
            literals = ["{" + ", ".join(f"0x{x:02x}" for x in value) + "}"
                        for value in (before, after)]
            lines.append(f"    {{0x{off:x}, {literals[0]}, {literals[1]}}},")
        lines.append("};")
    lines.append("static const struct profile profiles[] = {")
    for index, p in enumerate(document["profiles"]):
        lines.append(f'    {{"{p["build"]}", {p["size"]}, {p["paths"]},')
        lines.append(f'     "{p["source_sha256"]}", "{p["result_sha256"]}",')
        lines.append(f'     registry_patches_{index}, {len(p["patches"])}}},')
    lines.append("};")
    Path(destination).write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    root = Path(__file__).resolve().parents[1] / "ramdisk"
    generate_header(root / "keybagd-profiles.json", root / "keybagd-profiles.h")
